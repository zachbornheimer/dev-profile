#!/usr/bin/env bash
# dev-profile-retire-legacy-hooks: hooks left by retired managers are renamed
# aside, git-lfs and unknown hooks stay, and a second run changes nothing.
# Usage: retire-legacy-hooks-fixture.sh <generated-dir>
set -euo pipefail
export HK=0 # no global git hooks inside the fixture repos

out="${1:?usage: retire-legacy-hooks-fixture.sh <generated-dir>}"
work="$(cd "$(mktemp -d)" && pwd -P)"
trap 'rm -rf "${work}"' EXIT
retire="${out}/bin/dev-profile-retire-legacy-hooks"
aside=".retired-by-dev-profile"

fail() {
	echo "FAIL retire-legacy-hooks fixture: $*" >&2
	exit 1
}

repo="${work}/repo"
git init -q "${repo}"
hooks="${repo}/.git/hooks"
printf '#!/bin/sh\ncall_lefthook run "pre-commit" "$@"\n' >"${hooks}/pre-commit"
printf '#!/bin/sh\n# managed by zq\nzq hook pre-push\n' >"${hooks}/pre-push"
printf '#!/bin/sh\ncommand -v git-lfs >/dev/null || exit 2\ngit lfs post-checkout "$@"\n' >"${hooks}/post-checkout"
printf '#!/bin/sh\necho my own hook\n' >"${hooks}/commit-msg"
printf '#!/bin/sh\n# yorkie 2.0.0\nexec yorkie-runner\n' >"${hooks}/prepare-commit-msg"
printf '#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n' >"${hooks}/post-merge"
printf '#!/usr/bin/env sh\nif [ "$SKIP_SIMPLE_GIT_HOOKS" = "1" ]; then exit 0; fi\nnpx simple-git-hooks\n' >"${hooks}/pre-merge-commit"
printf '#!/usr/bin/env sh\n. "$(dirname -- "$0")/_/husky.sh"\n' >"${hooks}/post-rewrite"
chmod +x "${hooks}"/*

(cd "${repo}" && "${retire}" --check) >"${work}/check.txt" 2>&1 || fail "--check must exit 0"
grep -Fq "pre-commit is a retired lefthook hook" "${work}/check.txt" || fail "--check must name the lefthook hook"
[[ -f "${hooks}/pre-commit" ]] || fail "--check must rename nothing"

"${retire}" "${repo}" >"${work}/first.txt" || fail "first run failed"
for hook in pre-commit pre-push prepare-commit-msg post-merge pre-merge-commit post-rewrite; do
	[[ ! -e "${hooks}/${hook}" && -f "${hooks}/${hook}${aside}" ]] || fail "${hook} must be renamed to ${hook}${aside}"
done
[[ -x "${hooks}/pre-commit${aside}" ]] || fail "a renamed hook keeps its content and mode"
for hook in post-checkout commit-msg; do
	[[ -f "${hooks}/${hook}" && ! -e "${hooks}/${hook}${aside}" ]] || fail "${hook} must stay"
done
[[ "$(wc -l <"${work}/first.txt" | tr -d ' ')" == 6 ]] || fail "first run must print the six renames"
grep -Fq "retired simple-git-hooks hook" "${work}/first.txt" || fail "first run must name the simple-git-hooks hook"

"${retire}" "${repo}" >"${work}/second.txt" || fail "second run failed"
[[ ! -s "${work}/second.txt" ]] || fail "second run must rename and print nothing"
(cd "${repo}" && "${retire}" --check) >"${work}/check2.txt" 2>&1
[[ ! -s "${work}/check2.txt" ]] || fail "--check must be silent once healed"

# A manager that rewrites its hook later is retired again without losing the first copy.
printf '#!/bin/sh\ncall_lefthook run "pre-commit" "$@"\n' >"${hooks}/pre-commit"
"${retire}" "${repo}" >/dev/null
[[ -f "${hooks}/pre-commit${aside}" && -f "${hooks}/pre-commit${aside}.1" ]] || fail "a second retirement must keep both copies"

# A linked worktree shares the main repo's hooks. The sample hooks are data, not
# code to run: a real git-lfs on PATH hangs in the post-checkout one.
git -C "${repo}" -c core.hooksPath=/dev/null -c user.name=t -c user.email=t@example.com -c commit.gpgsign=false commit -q --allow-empty -m init
git -C "${repo}" -c core.hooksPath=/dev/null worktree add -q "${work}/linked" -b linked
printf '#!/bin/sh\ncall_lefthook run "pre-push" "$@"\n' >"${hooks}/pre-push"
(cd "${work}/linked" && "${retire}") >/dev/null
[[ ! -e "${hooks}/pre-push" ]] || fail "run from a linked worktree must retire the shared hook"

# A repository-local core.hooksPath into a retired manager's directory (husky sets
# .husky/_) is unset; --check only warns; any other local hooksPath stays.
hp="${work}/hookspath"
git init -q "${hp}"
git -C "${hp}" config --local core.hooksPath .husky/_
(cd "${hp}" && "${retire}" --check) >"${work}/hp-check.txt" 2>&1
grep -Fq "core.hooksPath=.husky/_ points at a retired hook manager" "${work}/hp-check.txt" || fail "--check must warn about a husky core.hooksPath"
[[ "$(git -C "${hp}" config --local --get core.hooksPath)" == ".husky/_" ]] || fail "--check must leave core.hooksPath alone"
"${retire}" "${hp}" >"${work}/hp-first.txt"
grep -Fq "retired core.hooksPath .husky/_" "${work}/hp-first.txt" || fail "the run must report the unset hooksPath"
git -C "${hp}" config --local --get core.hooksPath >/dev/null && fail "a husky core.hooksPath must be unset"
"${retire}" "${hp}" >"${work}/hp-second.txt"
[[ ! -s "${work}/hp-second.txt" ]] || fail "a second run must change nothing"
git -C "${hp}" config --local core.hooksPath .my-own-hooks
"${retire}" "${hp}" >/dev/null
[[ "$(git -C "${hp}" config --local --get core.hooksPath)" == ".my-own-hooks" ]] || fail "an unrelated core.hooksPath must stay"

echo "retire-legacy-hooks fixture ok"
