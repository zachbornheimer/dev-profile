#!/usr/bin/env bash
set -euo pipefail
# Edit lib/pr.sh: `mise run generate` copies it into bin/.
bin_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"

# Publish the current branch as a GitHub PR: commit pending work, push without
# force, then reuse the open PR or create one. A branch with nothing to publish
# is skipped with exit 0, so `wt step for-each` can run this everywhere. Never
# prompts, so loops and scripts can drive it.
#   --draft     create the PR as a draft
#   --auto      mark the PR ready, then watch CI and merge it when green
#   -- CMD ...  run CMD in the worktree first; it makes the change to publish
#   DEV_PROFILE_PR_WATCH  tab|background: where --auto watches (default: a
#                         kitty tab when interactive in kitty, else background)
#   DEV_PROFILE_PR_MESSAGE  commit pending work with this message instead of
#                           one generated by the LLM (default: generated)
usage="usage: dev-profile-pr [--draft | --auto] [-- CMD ...]"
draft=false auto=false
while [[ $# -gt 0 ]]; do
	case "$1" in
	--draft) draft=true ;;
	--auto) auto=true ;;
	--)
		shift
		break
		;;
	*)
		echo "${usage}" >&2
		exit 2
		;;
	esac
	shift
done
if [[ "${draft}" == true && "${auto}" == true ]]; then
	echo "--draft and --auto conflict: GitHub cannot merge a draft. ${usage}" >&2
	exit 2
fi

branch="$(git symbolic-ref --quiet --short HEAD)" || {
	echo "Detached HEAD; check out a branch to publish" >&2
	exit 1
}
# shellcheck source=lib/sh/github.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/github.sh"

skip() {
	echo "Skipping ${branch}: $*"
	exit 0
}
[[ "${branch}" != "${default_branch}" ]] || skip "default branch"

for operation in MERGE_HEAD CHERRY_PICK_HEAD REVERT_HEAD rebase-merge rebase-apply; do
	if [[ -e "$(git rev-parse --git-path "${operation}")" ]]; then
		echo "Unfinished Git operation in ${branch}: ${operation}" >&2
		exit 1
	fi
done

# Never replace a different upstream.
upstream="$(git rev-parse --abbrev-ref --symbolic-full-name "@{upstream}" 2>/dev/null || :)"
if [[ -n "${upstream}" && "${upstream}" != "origin/${branch}" ]]; then
	echo "Unexpected upstream for ${branch}: ${upstream}" >&2
	exit 1
fi

# Stacked PRs target the branch recorded by `gh pr create --base`.
base="$(git config --get "branch.${branch}.gh-merge-base" || :)"
base="${base:-${default_branch}}"
git rev-parse --verify --quiet "origin/${base}" >/dev/null || {
	echo "origin/${base} not found; run git fetch origin" >&2
	exit 1
}

if [[ $# -gt 0 ]]; then
	"$@" || {
		echo "Command failed in ${branch}; worktree kept at ${PWD}" >&2
		exit 1
	}
	# A change that touched nothing leaves an empty worktree behind; drop it.
	if [[ -z "$(git status --porcelain)" && "$(git rev-list --count "origin/${base}..HEAD")" -eq 0 ]]; then
		wt remove --foreground "${branch}"
		skip "the command changed nothing; removed the worktree"
	fi
fi

url="$(branch_prs "${branch}" open | jq -r '.[0].url // empty')"
dirty="$(git status --porcelain)"

if [[ -z "${url}" && -z "${dirty}" ]]; then
	# A closed or merged PR with no commits since: nothing new to propose.
	last="$(branch_prs "${branch}" all | jq -c '.[0] // empty')"
	if [[ -n "${last}" && "$(jq -r .headRefOid <<<"${last}")" == "$(git rev-parse HEAD)" ]]; then
		skip "PR #$(jq -r .number <<<"${last}") is $(jq -r '.state | ascii_downcase' <<<"${last}") with no commits since"
	fi
fi

if [[ -n "${dirty}" ]]; then
	commit=(wt step commit)
	if [[ -n "${DEV_PROFILE_PR_MESSAGE:-}" ]]; then
		# wt still stages and runs its hooks; its message generator just prints
		# the given message.
		message_file="$(mktemp)"
		trap 'rm -f "${message_file}"' EXIT
		printf '%s\n' "${DEV_PROFILE_PR_MESSAGE}" >"${message_file}"
		commit+=(--config-set "commit.generation.command=\"cat >/dev/null; cat ${message_file}\"")
	fi
	"${commit[@]}"
	if [[ -n "$(git status --porcelain)" ]]; then
		echo "Uncommitted changes remain in ${branch}" >&2
		exit 1
	fi
fi

if [[ -z "${url}" ]]; then
	if wt list --full --format=json | jq -e --arg b "${branch}" '
    any(.items[]; .branch == $b and .default_branch.integration != null)
  ' >/dev/null; then
		skip "already integrated into ${default_branch}"
	fi
	[[ "$(git rev-list --count "origin/${base}..HEAD")" -gt 0 ]] || skip "no commits ahead of ${base}"
fi

git push --set-upstream origin "HEAD:refs/heads/${branch}"

if [[ -n "${url}" ]]; then
	echo "PR: ${url}"
else
	create=(ghr pr create --fill --head "${branch}" --base "${base}")
	[[ "${draft}" == false ]] || create+=(--draft)
	url="$("${create[@]}" | tail -n 1)"
	echo "PR: ${url}"
fi

[[ "${auto}" == true ]] || exit 0

if [[ "$(ghr pr view "${url}" --json isDraft --jq .isDraft)" == true ]]; then
	ghr pr ready "${url}"
fi

# Interactive in kitty: watch in a background tab. Loops and scripts: detach,
# so a batch of PRs does not open a tab each; notifications still arrive.
watcher="${bin_dir}/dev-profile-pr-watch"
where="${DEV_PROFILE_PR_WATCH:-}"
if [[ -z "${where}" ]]; then
	where=background
	if [[ -t 1 && -n "${KITTY_LISTEN_ON:-}" ]] && command -v kitten >/dev/null; then where=tab; fi
fi
if [[ "${where}" == tab ]]; then
	launch=(kitten @ --to "${KITTY_LISTEN_ON}" launch --type=tab --keep-focus
		--cwd "${PWD}" --env "PATH=${PATH}")
	[[ -z "${KITTY_WINDOW_ID:-}" ]] || launch+=(--match "id:${KITTY_WINDOW_ID}")
	"${launch[@]}" "${watcher}" "${url}" >/dev/null
	echo "Watching in a background kitty tab; it notifies on merge or CI failure"
else
	log="$(git rev-parse --path-format=absolute --git-common-dir)/wt/logs/pr-watch-${branch//\//-}.log"
	mkdir -p "$(dirname "${log}")"
	nohup "${watcher}" "${url}" >"${log}" 2>&1 </dev/null &
	echo "Watching in the background; log: ${log}"
fi
